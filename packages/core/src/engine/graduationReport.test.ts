// Regenerates docs/dev/graduations.md and graduations-cn.md from the
// code (English is canonical; the -cn file is its translation).
//
// This is the per-scale audit sheet: it lists, for every scale of both models,
// the measured interval source, the steps and levels of each segment, the
// printed numbers, and the row/display flags (adjacency, tickEdge, tick
// direction, numbers above/below). The "drawn ticks" line is the real output of
// getScaleTicks, so the document can never drift from the code.
//
// It runs as part of `npm test` and rewrites the files deterministically.
import { it } from 'vitest'
