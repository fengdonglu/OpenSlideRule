type Lang = typeof EN

function scaleBlock(s: ScaleDefinition, i: number, count: number, L: Lang): string[] {
  const out: string[] = []
  const ticks = getScaleTicks(s)
  const lv = { 1: 0, 2: 0, 3: 0 } as Record<number, number>
  for (const t of ticks) lv[t.level]++
  const labels = ticks.filter((t) => t.label).map((t) => t.label as string)
  const positions = ticks.map((t) => t.position)
  const pMin = positions.length ? Math.min(...positions) : 0
  const pMax = positions.length ? Math.max(...positions) : 0
  out.push(`### ${s.name} (type ${s.type})`)
  out.push(
    `- ${s.side} / ${s.section} / ${s.orientation} / ${s.isMovable ? L.label.slide : L.label.body}` +
      ` / ${L.label.adjacency}=${adjacencyOf(s, i, count)}` +
      ` / ${L.label.tickEdge}=${s.tickEdge ?? '-'}` +
      ` / ${L.label.ticks}=${L.label[tickDirection(s)]}` +
      ` / ${L.label.numbers}=${s.numbersBelow ? L.label.below : L.label.above}`,
  )
  if (s.sharedLabels?.length)
    out.push(`- ${L.label.shared}: ${s.sharedLabels.map((x) => x.name).join(', ')}`)
  if (s.notes?.length)
    out.push(
      `- ${L.label.notes}: ${s.notes
        .map((n) => (typeof n === 'string' ? n : n.map((p) => p.text).join('')))
        .join(' | ')}`,
    )
  out.push(
    `- ${L.label.drawn}: ${ticks.length} (L1=${lv[1]} L2=${lv[2]} L3=${lv[3]}), ` +
      `position ${pMin.toFixed(4)} .. ${pMax.toFixed(4)} (${L.label.span})`,
  )
  out.push(`- ${L.label.printed}: ${labels.join(' ')}`)
  if (s.calc) {
    const c = s.calc
    const flags = [`domain=${c.domain[0]}..${c.domain[1]}`]
    if ((c.decades ?? 1) > 1) flags.push(`decades=${c.decades}`)
    if (c.decreasing) flags.push('decreasing')
    out.push(`- ${L.label.source}: ScaleCalculation ${mapSummary(c.map)} ${flags.join(' ')}`)
    for (const iv of c.intervals) out.push(`  - [${iv.from}, ${iv.to}) ${stepsText(iv)}`)
    if (c.labels?.length)
      out.push(
        `  - ${L.label.printed}: ${c.labels
          .map((x) =>
            typeof x === 'number' ? (c.labelFormat?.(x) ?? defaultLabelFormat(x)) : x.text,
          )
          .join(' ')}`,
      )
    if (c.marks?.length)
      out.push(`  - ${L.label.marks}: ${c.marks.map((m) => `${m.value}=${m.label}`).join(' ')}`)
  }
  out.push('')
  return out
}

function sideSection(title: string, group: ScaleSectionGroup, L: Lang): string[] {
  const out = [`## ${title}`, '']
  for (const scales of [group.upper, group.middle, group.lower]) {
    scales.forEach((s, i) => out.push(...scaleBlock(s, i, scales.length, L)))
  }
  return out
}

function report(L: Lang): string {
  const lines: string[] = [
    L.h1,
    '',
    ...L.note,
    '',
    ...sideSection(L.titles.front1002, MODEL_1002.front, L),
    ...sideSection(L.titles.back1002, MODEL_1002.back, L),
    ...sideSection(L.titles.front57, MODEL_57.front, L),
  ]
  return lines.join('\n') + '\n'
}

it('regenerates docs/dev/graduations.md and graduations-cn.md', () => {
  writeFileSync('docs/dev/graduations.md', report(EN))
  writeFileSync('docs/dev/graduations-cn.md', report(CN))
})
